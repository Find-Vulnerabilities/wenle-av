//! The version resource: the strings a file's author chose to describe it with.
//!
//! # What it is
//!
//! Resource type 16 is `RT_VERSION`, and its payload is a `VS_VERSIONINFO`
//! structure — a small tree of length-prefixed nodes, each with a name and
//! optionally a value. Windows reads three things out of it: the fixed file
//! information (the four-part version number a shell shows in the properties
//! dialog), the translation table, and `StringFileInfo` — a table of
//! human-readable strings keyed by name.
//!
//! # Why a scanner cares
//!
//! Because it is the one place in an executable that contains *prose*, written
//! by whoever built the file, and it is generated by the linker from a resource
//! script the author had to write by hand. That makes it two things at once:
//!
//! - A **fingerprint**. The corpus's rules here are disjunctions of a company
//!   name against a product name against a file version against an internal
//!   name, and the combination is close to unique per build. A family that
//!   reuses one version resource across every sample is identified by it however
//!   much the code changes.
//! - A **lie detector**. Trojanised software carries the version resource of the
//!   program it is pretending to be, so the strings disagree with the file's own
//!   behaviour — and a rule that says "claims to be Mozilla, imports this, has
//!   this section layout" is a rule about the disagreement.
//!
//! # The shape of the tree
//!
//! Every node begins with the same six bytes and continues with a name, a value
//! and children, each aligned to four:
//!
//! ```text
//! WORD  wLength       the whole node, children included
//! WORD  wValueLength  the value, in *characters* when wType is 1 and in bytes
//!                     when it is 0
//! WORD  wType         0 for binary, 1 for text
//! WCHAR szKey[]       NUL-terminated, then padding to a four-byte boundary
//! ...   Value         wValueLength units
//! ...   Children      nodes of the same shape, until wLength is used up
//! ```
//!
//! The two structures that matter here:
//!
//! ```text
//! VS_VERSION_INFO          the root; its value is the 52-byte VS_FIXEDFILEINFO
//!  └ StringFileInfo        a container, no value
//!     └ 040904b0           a StringTable, no value; the name is a language and
//!        │                  code page in hex
//!        ├ CompanyName     a String: the name is the key, the value is the text
//!        ├ FileVersion
//!        └ ...
//! ```
//!
//! # Which nodes are entries
//!
//! Not "the leaves", and not "everything under a StringTable" — either would
//! need the walk to know the names of the containers, and a file is free to
//! spell them differently. The rule this module uses is a property of the node
//! itself: **a text node with a non-empty value is a string entry**. The
//! containers declare `wType` 1 with a zero `wValueLength`, and the translation
//! table declares a non-empty value with `wType` 0, so both drop out without a
//! name ever being compared. It is the reading that stays correct for a file
//! whose containers are named something this module has never seen.
//!
//! # Text, and what the value bytes are
//!
//! A value is `wValueLength` UTF-16 code units, and it reaches a rule as UTF-8.
//! The alternative — narrowing each code unit to one byte, which is what the
//! format's own `wType` distinction invites — is right only for the ASCII that
//! most version resources contain and turns every other name into mojibake. A
//! rule comparing against a company name is comparing against text the author
//! typed, and text that cannot be represented in the encoding is a reason to
//! decode it properly rather than to mangle it.
//!
//! # What a hostile file can do
//!
//! Every count in this structure is self-describing: a node's length covers its
//! own children, so a tree can be as deep as it likes and a length of zero is a
//! node that contains itself. The walk therefore carries a depth limit and a node
//! budget, and steps to the next sibling by the length it was given rather than
//! by one, so that a malformed length ends the walk instead of becoming an
//! infinite one.

use std::collections::HashMap;

use crate::pe::PeFile;
use crate::read::Reader;
use crate::resources::Resource;

/// `RT_VERSION`, the resource type the version information lives in.
const TYPE_VERSION: u32 = 16;

/// The six bytes of header every node begins with.
const HEADER_LEN: usize = 6;

/// How deep the tree may nest.
///
/// The real structure is four levels: root, `StringFileInfo`, a table, a string.
/// Six leaves room for the `VarFileInfo` branch and for a file that nests one
/// level further than the format describes, and stops a file that nests
/// thousands.
const MAX_DEPTH: usize = 6;

/// How many nodes the walk examines, across the whole resource.
///
/// A real version resource has a few dozen. The bound is here because the tree's
/// size is the file's to choose and a scanner reads files it did not write.
const MAX_NODES: usize = 1024;

/// The version information of a file, flattened to its string entries.
///
/// Empty for a file with no version resource, which is most files: a resource
/// script is something a project has to include deliberately, and malware
/// frequently does not. An empty one answers every key with `None`, which is
/// what a rule comparing a key against a value needs to see.
#[derive(Debug, Clone, Default)]
pub struct VersionInfo {
    /// Key to value, both as bytes. Keys are ASCII in every real resource and
    /// are compared exactly, which is what a rule indexing by a literal expects.
    entries: HashMap<Vec<u8>, Vec<u8>>,
    /// How many nodes the walk examined, entries or not.
    nodes: usize,
}

impl VersionInfo {
    /// The value of a string entry, or `None` when the key is not present.
    ///
    /// Case-sensitive, and deliberately: the keys are a fixed vocabulary a rule
    /// author writes out in full, and a lookup that ignored case would answer
    /// `pe.version_info["companyname"]` from a file that spells it
    /// `CompanyName` — a rule that matches where the one it was translated from
    /// did not. Being stricter than the source of a rule is the direction that
    /// produces missed detections, which are visible; the other direction
    /// produces false positives, which are what erode a user's trust in the
    /// product.
    pub fn get(&self, key: &[u8]) -> Option<&[u8]> {
        self.entries.get(key).map(Vec::as_slice)
    }

    /// How many distinct keys the resource declared.
    pub fn len(&self) -> usize {
        self.entries.len()
    }

    /// Whether there is no version resource, or one with no string entries.
    pub fn is_empty(&self) -> bool {
        self.entries.is_empty()
    }

    /// How many nodes were examined, entries or not.
    ///
    /// The number that shows a walk which stopped at its budget rather than at
    /// the end of the structure.
    pub fn nodes(&self) -> usize {
        self.nodes
    }

    /// The keys, in no particular order.
    pub fn keys(&self) -> impl Iterator<Item = &[u8]> {
        self.entries.keys().map(Vec::as_slice)
    }
}

/// Read a file's version information.
///
/// `resources` is the file's already-flattened resource tree — the leaves, not
/// the tree, because the flattening is what finds the version resource and
/// doing it twice per file to save an argument would be paying on every scan to
/// shorten a signature.
pub fn read(pe: &PeFile<'_>, resources: &[Resource<'_>]) -> VersionInfo {
    let mut info = VersionInfo::default();
    let data = pe.data();
    for resource in resources {
        if resource.type_id != Some(TYPE_VERSION) {
            continue;
        }
        // The length is the file's number and is not clamped here: a resource
        // whose data entry claims more than the file holds is a resource this
        // walk cannot read, and the slice is what decides that.
        let Ok(start) = usize::try_from(resource.offset) else {
            continue;
        };
        let Ok(len) = usize::try_from(resource.length) else {
            continue;
        };
        let Some(window) = data.get(start..start.saturating_add(len)) else {
            continue;
        };
        // The first readable version resource wins. A file can carry one per
        // language, and a rule asking for `CompanyName` is asking what the file
        // says it is; the answer that agrees with what a shell would show is the
        // first one in the tree, which is the one the loader prefers.
        let mut walker = Walker::new(window);
        walker.walk(0, window.len(), 0);
        info.nodes = walker.nodes;
        info.entries = walker.entries;
        if !info.entries.is_empty() {
            return info;
        }
        // A resource that yielded nothing is kept only if no later one yields
        // something, so the node count is carried forward rather than reset.
        info.nodes = walker.nodes;
    }
    info
}

/// The state of one walk over one version resource.
struct Walker<'a> {
    reader: Reader<'a>,
    entries: HashMap<Vec<u8>, Vec<u8>>,
    nodes: usize,
}

impl<'a> Walker<'a> {
    fn new(data: &'a [u8]) -> Self {
        Self {
            reader: Reader::new(data),
            entries: HashMap::new(),
            nodes: 0,
        }
    }

    /// Walk the nodes that lie in `[at, end)`.
    ///
    /// The range is the parent's declared extent, which is what bounds the walk
    /// from above: a child that claims to be longer than its parent is read up to
    /// the parent's end rather than past it.
    fn walk(&mut self, mut at: usize, end: usize, depth: usize) {
        while at + HEADER_LEN <= end {
            if self.nodes >= MAX_NODES || depth > MAX_DEPTH {
                return;
            }
            // A node whose length does not cover its own header cannot be
            // stepped over, and stepping by anything else would either loop
            // forever or walk into the middle of the next node. It ends the
            // walk, which is the only answer that cannot be wrong.
            let Ok(length) = self.reader.u16(at) else {
                return;
            };
            let length = length as usize;
            if length < HEADER_LEN {
                return;
            }
            let node_end = at.saturating_add(length).min(end);
            self.nodes += 1;

            let value_length = self.reader.u16(at + 2).unwrap_or(0) as usize;
            let is_text = self.reader.u16(at + 4).unwrap_or(0) == 1;

            // The name, from just past the header to the node's end. A name with
            // no NUL in it runs to the end of the window, which makes `key` the
            // rest of the node — and the alignment below then lands past the
            // node, so nothing is read out of it.
            let key_at = at + HEADER_LEN;
            let key_bytes = name_len(&self.reader, key_at);
            let key = self.reader.utf16(key_at, key_bytes / 2).unwrap_or_default();
            let after_key = align4(key_at + key_bytes);

            // A value is a count of units when the node is text and a count of
            // bytes when it is binary. Both are the file's number, so both are
            // clamped to what is left of the node.
            let value_bytes = if is_text {
                value_length.saturating_mul(2)
            } else {
                value_length
            };
            let value_at = after_key;
            let children_at = align4(value_at.saturating_add(value_bytes)).min(node_end);

            // The entry test: text, with a value. See the module docs for why
            // this is a property of the node rather than of where it sits.
            if is_text && value_length > 0 && !key.is_empty() {
                if let Ok(value) = self.reader.utf16(value_at, value_length) {
                    // `entry` rather than `insert`: the first table in the tree
                    // is the one a shell displays, and a file with several
                    // translations gives the same key more than once.
                    self.entries
                        .entry(key.into_bytes())
                        .or_insert_with(|| value.into_bytes());
                }
            }

            self.walk(children_at, node_end, depth + 1);
            at = node_end;
        }
    }
}

/// The next offset at or after `offset` that is a multiple of four.
fn align4(offset: usize) -> usize {
    offset.saturating_add(3) & !3
}

/// How many bytes a NUL-terminated UTF-16 name at `offset` occupies, its
/// terminator included.
///
/// Counted in units rather than through the decoded `String`, because a name
/// containing a surrogate pair is two units and one `char`, and a walk that
/// aligned on the character count would step two bytes into the value. The
/// count is of what is *in the file*, which is the thing the format's alignment
/// rule is about.
///
/// A name with no terminator before the end of the buffer is reported as running
/// to that end. The caller clamps the offsets it computes from this to the node
/// it is reading, so an unterminated name makes the node unreadable rather than
/// making it read past itself.
fn name_len(reader: &Reader<'_>, offset: usize) -> usize {
    let mut len = 0;
    while let Ok(unit) = reader.u16(offset + len) {
        if unit == 0 {
            return len + 2;
        }
        len += 2;
    }
    len
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::resources;
    use crate::testing::ResourceSpec;
    use crate::testing::{add_resources, minimal_pe32, version_node, version_resource};

    /// Run `f` over the version information of an image carrying `blob` as a
    /// resource of type `type_id`.
    ///
    /// The blob goes into a real resource tree rather than being handed to the
    /// reader directly, because that is how it reaches the reader in production:
    /// the walk starts from a leaf of the resource directory, and a test that
    /// skipped the tree would be testing a path this crate does not have.
    fn with_info<T>(blob: &[u8], type_id: u32, f: impl FnOnce(&VersionInfo) -> T) -> T {
        let mut data = minimal_pe32();
        add_resources(
            &mut data,
            &[ResourceSpec::new(type_id, 1u32, &[1033u32], blob)],
        );
        let pe = PeFile::parse(&data).expect("the fixture is a PE");
        let resources = resources::read(&pe);
        f(&read(&pe, resources.leaves()))
    }

    /// The same, over the tree [`version_resource`] builds.
    fn with_entries<T>(entries: &[(&str, &str)], f: impl FnOnce(&VersionInfo) -> T) -> T {
        with_info(&version_resource(entries), TYPE_VERSION, f)
    }

    #[test]
    fn a_string_entry_is_read_by_its_key() {
        with_entries(
            &[
                ("CompanyName", "Microsoft Corporation"),
                ("FileVersion", "10.0.19041.1"),
            ],
            |info| {
                assert_eq!(
                    info.get(b"CompanyName"),
                    Some(&b"Microsoft Corporation"[..])
                );
                assert_eq!(info.get(b"FileVersion"), Some(&b"10.0.19041.1"[..]));
                assert_eq!(info.len(), 2);
            },
        );
    }

    #[test]
    fn the_containers_are_not_entries() {
        // All three structural nodes are in the tree and none of them is a key
        // a rule can ask for. The root's value is binary and the two
        // containers' are empty, which is what drops them — no name is compared
        // to decide it.
        with_entries(&[("InternalName", "SERVICE.EXE")], |info| {
            assert!(info.get(b"VS_VERSION_INFO").is_none());
            assert!(info.get(b"StringFileInfo").is_none());
            assert!(info.get(b"040904b0").is_none());
            assert_eq!(info.len(), 1);
        });
    }

    #[test]
    fn a_key_that_is_not_present_is_none() {
        with_entries(&[("CompanyName", "Acme")], |info| {
            assert!(info.get(b"ProductName").is_none());
            // And case matters, which is the deliberate half of the choice: a
            // rule that spells the key differently than the file does must not
            // match, because the rule it was translated from would not have.
            assert!(info.get(b"companyname").is_none());
        });
    }

    #[test]
    fn a_value_that_is_not_ascii_survives_the_decode() {
        // Narrowing each code unit to a byte would turn this into mojibake, and
        // mojibake is a string no rule can be written against.
        let name = "\u{5317}\u{4eac}\u{516c}\u{53f8}";
        with_entries(&[("CompanyName", name)], |info| {
            assert_eq!(
                info.get(b"CompanyName")
                    .and_then(|v| std::str::from_utf8(v).ok()),
                Some(name)
            );
        });
    }

    #[test]
    fn a_file_with_no_version_resource_has_no_entries() {
        let data = minimal_pe32();
        let pe = PeFile::parse(&data).expect("the fixture is a PE");
        let info = read(&pe, &[]);
        assert!(info.is_empty());
        assert_eq!(info.len(), 0);
        assert_eq!(info.nodes(), 0);
        assert!(info.get(b"CompanyName").is_none());
    }

    #[test]
    fn another_resource_type_is_not_read_as_version_information() {
        // Resource type 10 is `RCDATA`, which is where a dropper puts a
        // payload. Reading it as a version resource would walk a structure that
        // is not one and report entries the file never declared.
        with_info(&version_resource(&[("CompanyName", "Acme")]), 10, |info| {
            assert!(info.is_empty(), "only type 16 is version information");
        });
    }

    #[test]
    fn a_node_whose_length_is_zero_ends_the_walk() {
        // A zero length is a node that contains itself. The walk has to stop
        // rather than step forward and find the same zero again.
        let mut blob = version_node(
            "StringFileInfo",
            1,
            &[],
            &version_node("040904b0", 1, &[], &[]),
        );
        blob[0..2].copy_from_slice(&0u16.to_le_bytes());
        with_info(&blob, TYPE_VERSION, |info| {
            assert!(info.is_empty());
            assert_eq!(info.nodes(), 0, "a node below the header is not counted");
        });
    }

    #[test]
    fn a_tree_that_nests_too_far_stops_at_the_limit() {
        // Each level is a container, so nothing is recorded and the only
        // visible effect of the depth limit is that the walk ends. The value is
        // buried forty levels down, well past `MAX_DEPTH`.
        let mut blob = version_node("leaf", 1, &crate::testing::utf16_bytes("deep"), &[]);
        for _ in 0..40 {
            blob = version_node("container", 1, &[], &blob);
        }
        with_info(&blob, TYPE_VERSION, |info| {
            assert!(info.nodes() <= MAX_NODES, "the budget bounds the walk");
            assert!(info.is_empty(), "a value past the depth limit is not read");
        });
    }

    #[test]
    fn a_value_that_runs_past_its_node_is_not_read_past_it() {
        // The declared value length is larger than the node holding it. The
        // clamp is the node's own length, so the read stops inside the resource
        // rather than walking off the end of the buffer.
        let mut blob = version_resource(&[("CompanyName", "Acme")]);
        // The `CompanyName` node's `wValueLength`, found by its key rather than
        // by an offset computed here: an offset would be a second copy of the
        // layout that could drift from the builder's.
        let at = find(&blob, b"C\0o\0m\0p\0a\0n\0y\0N\0a\0m\0e\0").expect("the key is in the blob");
        blob[at - 4..at - 2].copy_from_slice(&0xFFFFu16.to_le_bytes());
        with_info(&blob, TYPE_VERSION, |info| {
            assert!(info.nodes() <= MAX_NODES);
        });
    }

    /// The offset of `needle` in `haystack`, as UTF-16LE bytes.
    fn find(haystack: &[u8], needle: &[u8]) -> Option<usize> {
        haystack
            .windows(needle.len())
            .position(|window| window == needle)
    }

    #[test]
    fn the_first_of_two_tables_wins() {
        // A file with two translations: the same key twice. The first table is
        // the one a shell shows, and it is the one a rule should see.
        let first = version_node(
            "040904b0",
            1,
            &[],
            &version_node("CompanyName", 1, &crate::testing::utf16_bytes("First"), &[]),
        );
        let second = version_node(
            "040904b1",
            1,
            &[],
            &version_node(
                "CompanyName",
                1,
                &crate::testing::utf16_bytes("Second"),
                &[],
            ),
        );
        let mut children = first;
        children.extend_from_slice(&second);
        let blob = version_node(
            "VS_VERSION_INFO",
            0,
            &[0u8; 52],
            &version_node("StringFileInfo", 1, &[], &children),
        );
        with_info(&blob, TYPE_VERSION, |info| {
            assert_eq!(info.get(b"CompanyName"), Some(&b"First"[..]));
            assert_eq!(info.len(), 1, "one key, not one per table");
        });
    }

    #[test]
    fn alignment_is_to_four_bytes() {
        assert_eq!(align4(0), 0);
        assert_eq!(align4(4), 4);
        assert_eq!(align4(5), 8);
        assert_eq!(align4(7), 8);
        assert_eq!(align4(8), 8);
    }

    #[test]
    fn the_builder_and_the_reader_agree_about_the_layout() {
        // The fixture in `testing` and the walk here are written separately, so
        // a key the builder wrote at one offset and the reader looked for at
        // another would show up as a missing entry rather than as a passing test
        // that proves nothing. Four keys of different lengths, because the
        // alignment rule is what differs between them.
        with_entries(
            &[
                ("A", "1"),
                ("CompanyName", "Acme"),
                ("FileVersion", "1.2.3.4"),
                ("LegalCopyright", "(c) Acme"),
            ],
            |info| {
                assert_eq!(info.len(), 4);
                assert_eq!(info.get(b"A"), Some(&b"1"[..]));
                assert_eq!(info.get(b"LegalCopyright"), Some(&b"(c) Acme"[..]));
            },
        );
    }
}
